/**
 * Intelligent AI Playlist Maker Bottom Sheet.
 *
 * Triggered by long-pressing the Explore tab:
 * Gathers user tracks from library / listening history and uses AI vibe heuristics
 * to generate a cohesive bespoke smart playlist, saving it directly to local or cloud playlists.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AiPlaylistMakerSheet(
    availableSongs: List<Song>,
    onDismiss: () -> Unit,
    onCreatePlaylist: (title: String, songIds: List<String>, songs: List<Song>, playImmediately: Boolean) -> Unit,
) {
    val sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)
    val scope = rememberCoroutineScope()

    var customPrompt by remember { mutableStateOf("") }
    var selectedVibe by remember { mutableStateOf("⚡ Workout Energy") }
    var isGenerating by remember { mutableStateOf(false) }
    var playlistTitle by remember { mutableStateOf("Workout Energy • AI Mix") }
    val curatedSongs = remember { mutableStateListOf<Song>() }
    var hasGenerated by remember { mutableStateOf(false) }

    val vibes = listOf(
        "⚡ Workout Energy" to listOf("workout", "energy", "pump", "power", "run", "fast", "bass", "beat", "hype", "club", "dance", "electronic", "rock"),
        "🌙 Late Night Chill" to listOf("night", "chill", "calm", "slow", "ambient", "dream", "quiet", "sleep", "moon", "lo-fi", "r&b", "soul"),
        "☕ Focus & Deep Work" to listOf("focus", "study", "work", "instrumental", "piano", "jazz", "lofi", "beats", "peace", "flow"),
        "✨ Nostalgia Hits" to listOf("classic", "old", "remember", "retro", "summer", "golden", "timeless", "love", "memory", "acoustic"),
        "🌧 Melancholy Rain" to listOf("sad", "rain", "cry", "lonely", "dark", "heart", "tears", "blue", "acoustic", "autumn"),
        "🔥 Party Bangers" to listOf("party", "hit", "fire", "drop", "summer", "dance", "wild", "turn", "radio", "pop", "remix"),
    )

    fun generatePlaylist(vibeName: String, query: String) {
        scope.launch {
            isGenerating = true
            delay(500) // Fluid generation animation

            val keywords = (vibes.find { it.first == vibeName }?.second ?: emptyList()) +
                query.lowercase(Locale.ROOT).split(" ", ",", "-", "_").filter { it.length > 2 }

            // Score and rank songs based on keywords matching song title, artist, or album
            val scored = availableSongs.map { song ->
                val fullText = "${song.title} ${song.artist} ${song.album.orEmpty()}".lowercase(Locale.ROOT)
                var score = 0
                for (kw in keywords) {
                    if (fullText.contains(kw)) score += 3
                }
                // Add natural variation so playlists are fresh
                val hashScore = (song.videoId.hashCode() and 0x7FFFFFFF) % 5
                song to (score + hashScore)
            }

            val ranked = scored.sortedByDescending { it.second }.map { it.first }
            val chosen = (if (ranked.size >= 12) ranked.take(24) else availableSongs.shuffled().take(20)).distinctBy { it.videoId }

            curatedSongs.clear()
            curatedSongs.addAll(chosen)

            playlistTitle = when {
                query.isNotBlank() -> "${query.trim().replaceFirstChar { it.uppercase() }} • AI Mix"
                else -> "${vibeName.replace(Regex("[^a-zA-Z &]"), "").trim()} • AI Mix"
            }
            hasGenerated = true
            isGenerating = false
        }
    }

    // Auto-generate initial playlist on first show
    remember {
        if (!hasGenerated && availableSongs.isNotEmpty()) {
            generatePlaylist(selectedVibe, "")
        }
    }

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = sheetState,
        containerColor = MaterialTheme.colorScheme.surfaceContainerHigh,
        shape = RoundedCornerShape(topStart = 32.dp, topEnd = 32.dp),
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .fillMaxHeight(0.92f)
                .navigationBarsPadding()
                .padding(horizontal = 20.dp),
        ) {
            // Header with AI gradient emblem
            Row(
                modifier = Modifier.fillMaxWidth().padding(bottom = 12.dp),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Box(
                        modifier = Modifier
                            .size(36.dp)
                            .clip(CircleShape)
                            .background(
                                Brush.linearGradient(
                                    listOf(Color(0xFFFF6E40), Color(0xFFB388FF), Color(0xFF00E5FF)),
                                ),
                            ),
                        contentAlignment = Alignment.Center,
                    ) {
                        Icon(
                            imageVector = Icons.Default.AutoAwesome,
                            contentDescription = null,
                            tint = Color.White,
                            modifier = Modifier.size(20.dp),
                        )
                    }
                    Spacer(Modifier.width(12.dp))
                    Column {
                        Text(
                            text = "AI Playlist Maker",
                            style = MaterialTheme.typography.titleLarge,
                            fontWeight = FontWeight.Bold,
                            color = MaterialTheme.colorScheme.onSurface,
                        )
                        Text(
                            text = "Curate bespoke playlists from your music library",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
                IconButton(onClick = onDismiss) {
                    Icon(
                        imageVector = Icons.Default.Close,
                        contentDescription = "Close",
                        tint = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }

            // Vibe Pills Carousel
            Text(
                text = "Choose a Vibe",
                style = MaterialTheme.typography.labelMedium,
                fontWeight = FontWeight.SemiBold,
                color = MaterialTheme.colorScheme.primary,
                modifier = Modifier.padding(top = 4.dp, bottom = 8.dp),
            )
            LazyRow(
                horizontalArrangement = Arrangement.spacedBy(8.dp),
                contentPadding = PaddingValues(horizontal = 2.dp),
            ) {
                items(vibes) { (vibe, _) ->
                    val isSelected = selectedVibe == vibe
                    Box(
                        modifier = Modifier
                            .clip(RoundedCornerShape(20.dp))
                            .background(
                                if (isSelected) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.surfaceVariant,
                            )
                            .m3eSquish()
                            .clickable {
                                selectedVibe = vibe
                                generatePlaylist(vibe, customPrompt)
                            }
                            .padding(horizontal = 14.dp, vertical = 9.dp),
                    ) {
                        Text(
                            text = vibe,
                            style = MaterialTheme.typography.labelMedium,
                            fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Medium,
                            color = if (isSelected) MaterialTheme.colorScheme.onPrimary else MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
            }

            Spacer(Modifier.height(14.dp))

            // Custom prompt text field
            OutlinedTextField(
                value = customPrompt,
                onValueChange = {
                    customPrompt = it
                },
                placeholder = {
                    Text("Or describe any custom mood, tempo or genre...")
                },
                trailingIcon = {
                    Box(
                        modifier = Modifier
                            .clip(CircleShape)
                            .background(MaterialTheme.colorScheme.primary)
                            .m3eSquish()
                            .clickable { generatePlaylist(selectedVibe, customPrompt) }
                            .padding(8.dp),
                    ) {
                        Icon(
                            imageVector = Icons.Default.AutoAwesome,
                            contentDescription = "Generate",
                            tint = MaterialTheme.colorScheme.onPrimary,
                            modifier = Modifier.size(18.dp),
                        )
                    }
                },
                modifier = Modifier.fillMaxWidth(),
                shape = RoundedCornerShape(18.dp),
                colors = OutlinedTextFieldDefaults.colors(
                    focusedBorderColor = MaterialTheme.colorScheme.primary,
                    unfocusedBorderColor = MaterialTheme.colorScheme.outlineVariant.copy(alpha = 0.5f),
                ),
                singleLine = true,
            )

            Spacer(Modifier.height(16.dp))

            // Playlist Title & Results
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Column(Modifier.weight(1f)) {
                    Text(
                        text = playlistTitle,
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface,
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis,
                    )
                    Text(
                        text = "${curatedSongs.size} tracks curated for you",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
                if (isGenerating) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(24.dp),
                        strokeWidth = 2.5.dp,
                        color = MaterialTheme.colorScheme.primary,
                    )
                }
            }

            Spacer(Modifier.height(10.dp))

            // Curated Tracklist Preview
            LazyColumn(
                modifier = Modifier
                    .weight(1f)
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(22.dp))
                    .background(MaterialTheme.colorScheme.surfaceContainer)
                    .padding(8.dp),
                verticalArrangement = Arrangement.spacedBy(6.dp),
            ) {
                itemsIndexed(curatedSongs) { index, song ->
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .clip(RoundedCornerShape(14.dp))
                            .background(MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.6f))
                            .padding(8.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        AsyncImage(
                            model = song.thumbnailUrl,
                            contentDescription = null,
                            contentScale = ContentScale.Crop,
                            modifier = Modifier
                                .size(44.dp)
                                .clip(RoundedCornerShape(10.dp)),
                        )
                        Spacer(Modifier.width(12.dp))
                        Column(Modifier.weight(1f)) {
                            Text(
                                text = song.title,
                                style = MaterialTheme.typography.bodyMedium,
                                fontWeight = FontWeight.SemiBold,
                                color = MaterialTheme.colorScheme.onSurface,
                                maxLines = 1,
                                overflow = TextOverflow.Ellipsis,
                            )
                            Text(
                                text = song.artist,
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                maxLines = 1,
                                overflow = TextOverflow.Ellipsis,
                            )
                        }
                        IconButton(
                            onClick = { curatedSongs.removeAt(index) },
                            modifier = Modifier.size(32.dp),
                        ) {
                            Icon(
                                imageVector = Icons.Default.Close,
                                contentDescription = "Remove",
                                tint = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.7f),
                                modifier = Modifier.size(16.dp),
                            )
                        }
                    }
                }
            }

            Spacer(Modifier.height(14.dp))

            // Action Buttons: Save & Play
            Row(
                modifier = Modifier.fillMaxWidth().padding(bottom = 12.dp),
                horizontalArrangement = Arrangement.spacedBy(10.dp),
            ) {
                // Save Only button
                Box(
                    modifier = Modifier
                        .weight(1f)
                        .clip(RoundedCornerShape(24.dp))
                        .background(MaterialTheme.colorScheme.surfaceVariant)
                        .expressiveClickable(enabled = curatedSongs.isNotEmpty()) {
                            onCreatePlaylist(
                                playlistTitle,
                                curatedSongs.map { it.videoId },
                                curatedSongs.toList(),
                                false,
                            )
                            onDismiss()
                        }
                        .padding(vertical = 14.dp),
                    contentAlignment = Alignment.Center,
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(
                            imageVector = Icons.Default.Save,
                            contentDescription = null,
                            tint = MaterialTheme.colorScheme.onSurfaceVariant,
                            modifier = Modifier.size(18.dp),
                        )
                        Spacer(Modifier.width(8.dp))
                        Text(
                            text = "Save Playlist",
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.Bold,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }

                // Save & Play Immediately button
                Box(
                    modifier = Modifier
                        .weight(1.3f)
                        .clip(RoundedCornerShape(24.dp))
                        .background(MaterialTheme.colorScheme.primary)
                        .expressiveClickable(enabled = curatedSongs.isNotEmpty()) {
                            onCreatePlaylist(
                                playlistTitle,
                                curatedSongs.map { it.videoId },
                                curatedSongs.toList(),
                                true,
                            )
                            onDismiss()
                        }
                        .padding(vertical = 14.dp),
                    contentAlignment = Alignment.Center,
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(
                            imageVector = Icons.Default.PlayArrow,
                            contentDescription = null,
                            tint = MaterialTheme.colorScheme.onPrimary,
                            modifier = Modifier.size(20.dp),
                        )
                        Spacer(Modifier.width(8.dp))
                        Text(
                            text = "Save & Play Now",
                            style = MaterialTheme.typography.labelLarge,
                            fontWeight = FontWeight.Bold,
                            color = MaterialTheme.colorScheme.onPrimary,
                        )
                    }
                }
            }
        }
    }
}
